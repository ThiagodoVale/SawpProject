    if len(sig) == 0:
        print(f"No links with q <= {ALPHA_LEVEL:.2f}. Check S6_PCMCI_all_links.csv for exploratory p-values.")
    else:
        print(sig[["source", "target", "lag_years", "partial_corr", "p_value", "q_fdr"]].to_string(index=False))

    print("\nPlotting PCMCI graph...")
    graph_path = plot_pcmci_graph(results)

    print("Plotting lag functions...")
    lag_path = plot_lag_function(results)

    summary_path = write_summary(df, links, graph_path, lag_path, results["method_name"])

    print("\nDone.")
    print(f"Input table: {FIG_DIR / 'S6_PCMCI_input_AMJJ_normalized_series.csv'}")
    print(f"All links: {out_all}")
    print(f"Significant links: {out_sig}")
    print(f"Graph: {graph_path}")
    print(f"Lag functions: {lag_path}")
    print(f"Summary: {summary_path}")
