"""
PCMCI causal analysis for the SAWP-ENEB mechanism.

This script uses the AMJJ annual normalized anomalies generated by the
SAWP-ENEB diagnostic script and applies PCMCI/PCMCI+ from Tigramite.

Variables tested
----------------
1. SAWP SST
2. SAWP surface wind speed
3. Low-level precipitable water, 1000-850 hPa
4. NEB omega/w
5. ENEB rainfall

Physical hypothesis
-------------------
SAWP SST -> surface wind -> low-level water vapor -> vertical motion -> ENEB rainfall

Important note
--------------
With AMJJ annual data, the sample is short (~60 years). Interpret PCMCI as an
exploratory causal-screening analysis, not as definitive proof of causality.
For stronger results, repeat this analysis with monthly data and seasonal controls.
"""


import os
import sys
import json
import subprocess
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ============================================================
# USER CONFIGURATION
# ============================================================

BASE_DIR = Path(".")
FIG_DIR = BASE_DIR / "figuras_revisor"
FIG_DIR.mkdir(parents=True, exist_ok=True)

# Previous diagnostic script. Keep it in the same folder as this PCMCI script.
SOURCE_SCRIPT = Path("script_painel_separado_mapas_series_sawp_eneb_v3_series_corrigidas.py")

# PCMCI parameters
TAU_MIN = 0
TAU_MAX = 2          # Annual AMJJ lags. 1 = previous AMJJ season, 2 = two years before.
PC_ALPHA = 0.20      # Liberal preselection for small samples.
ALPHA_LEVEL = 0.10   # Significance level shown in the output graph.
USE_PCMCI_PLUS = True

# Optional: install Tigramite automatically if missing.
AUTO_INSTALL_TIGRAMITE = True

# Variables taken from event_table.
# Keep order physically interpretable.
VAR_COLUMNS = [
    "sst_norm",
    "wind_norm",
    "pw_low_norm",
    "omega_neb_norm",
    "rain_norm",
]

VAR_NAMES = [
    "SAWP_SST",
    "SAWP_wind",
    "LL_PW_1000_850",
    "NEB_omega",
    "ENEB_rain",
]

# For omega, ERA5 pressure velocity convention: negative omega = ascent.
# Keep the raw normalized omega by default. If you prefer positive = ascent,
# set this True and the script will multiply omega by -1.
USE_ASCENT_INSTEAD_OF_OMEGA = False

# ============================================================
# UTILITIES
# ============================================================

def ensure_tigramite():
    try:
        from tigramite import data_processing as pp  # noqa: F401
        from tigramite.pcmci import PCMCI  # noqa: F401
        from tigramite.independence_tests.parcorr import ParCorr  # noqa: F401
        from tigramite import plotting as tp  # noqa: F401
        return
    except ImportError:
        if not AUTO_INSTALL_TIGRAMITE:
            raise SystemExit(
                "Tigramite is not installed. Install it with:\n\n"
                "    pip install tigramite\n\n"
                "or set AUTO_INSTALL_TIGRAMITE = True inside this script."
            )
        subprocess.check_call([sys.executable, "-m", "pip", "install", "tigramite"])


def load_source_module():
    if not SOURCE_SCRIPT.exists():
        raise FileNotFoundError(
            f"Could not find {SOURCE_SCRIPT}. Put this PCMCI script in the same folder "
            "as script_painel_separado_mapas_series_sawp_eneb_v3_series_corrigidas.py"
        )

    spec = importlib.util.spec_from_file_location("sawp_eneb_series_source", str(SOURCE_SCRIPT))
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def load_event_table() -> pd.DataFrame:
    """Build or read the AMJJ annual table used by PCMCI."""
    csv_path = FIG_DIR / "S5_event_table_sawp_sst_eneb_rainfall.csv"

    # Prefer rebuilding because the latest script contains wind, omega, and low-level PW.
    module = load_source_module()
    df = module.build_event_table()

    missing = [c for c in VAR_COLUMNS if c not in df.columns]
    if missing:
        raise KeyError(
            "The event table does not contain the required variables: "
            + ", ".join(missing)
            + "\nCheck whether you are using the v3 script with wind, omega and low-level PW."
        )

    df = df.copy()
    if USE_ASCENT_INSTEAD_OF_OMEGA:
        df["omega_neb_norm"] = -df["omega_neb_norm"]

    df = df[VAR_COLUMNS].replace([np.inf, -np.inf], np.nan).dropna()
    df.index = df.index.astype(int)
    df.to_csv(FIG_DIR / "S6_PCMCI_input_AMJJ_normalized_series.csv")
    return df


def run_pcmci(df: pd.DataFrame):
    ensure_tigramite()

    from tigramite import data_processing as pp
    from tigramite.pcmci import PCMCI
    from tigramite.independence_tests.parcorr import ParCorr

    data = df.values.astype(float)

    dataframe = pp.DataFrame(
        data,
        datatime=np.asarray(df.index),
        var_names=VAR_NAMES,
    )

    parcorr = ParCorr(significance="analytic")
    pcmci = PCMCI(dataframe=dataframe, cond_ind_test=parcorr, verbosity=1)

    if USE_PCMCI_PLUS and hasattr(pcmci, "run_pcmciplus"):
        results = pcmci.run_pcmciplus(
            tau_min=TAU_MIN,
            tau_max=TAU_MAX,
            pc_alpha=PC_ALPHA,
        )
        method_name = "PCMCIplus"
    else:
        results = pcmci.run_pcmci(
            tau_min=TAU_MIN,
            tau_max=TAU_MAX,
            pc_alpha=PC_ALPHA,
        )
        method_name = "PCMCI"

    q_matrix = pcmci.get_corrected_pvalues(
        p_matrix=results["p_matrix"],
        tau_min=TAU_MIN,
        tau_max=TAU_MAX,
        fdr_method="fdr_bh",
    )

    results["q_matrix"] = q_matrix
    results["method_name"] = method_name
    return pcmci, results


def save_link_tables(results: dict):
    val = results["val_matrix"]
    p = results["p_matrix"]
    q = results["q_matrix"]

    rows = []
    nvar = len(VAR_NAMES)
    for source in range(nvar):
        for target in range(nvar):
            for tau in range(TAU_MIN, TAU_MAX + 1):
                # Tigramite convention: source at lag tau -> target at time t.
                if source == target and tau == 0:
                    continue
                rows.append({
                    "source": VAR_NAMES[source],
                    "target": VAR_NAMES[target],
                    "lag_years": tau,
                    "partial_corr": float(val[source, target, tau]),
                    "p_value": float(p[source, target, tau]),
                    "q_fdr": float(q[source, target, tau]),
                    "significant_q_alpha": bool(q[source, target, tau] <= ALPHA_LEVEL),
                })

    links = pd.DataFrame(rows)
    links = links.sort_values(["q_fdr", "p_value", "source", "target", "lag_years"])

    out_all = FIG_DIR / "S6_PCMCI_all_links.csv"
    out_sig = FIG_DIR / f"S6_PCMCI_significant_links_q_le_{ALPHA_LEVEL:.2f}.csv"
    links.to_csv(out_all, index=False)
    links[links["significant_q_alpha"]].to_csv(out_sig, index=False)

    return links, out_all, out_sig


def plot_pcmci_graph(results: dict):
    from tigramite import plotting as tp

    graph_path = FIG_DIR / "S6_PCMCI_causal_graph.png"
    q_matrix = results["q_matrix"]
    val_matrix = results["val_matrix"]

    link_matrix = q_matrix <= ALPHA_LEVEL

    plt.figure(figsize=(10, 8))
    tp.plot_graph(
        val_matrix=val_matrix,
        link_matrix=link_matrix,
        var_names=VAR_NAMES,
        link_colorbar_label="Partial correlation",
        node_colorbar_label="Autocorrelation",
        figsize=(10, 8),
    )
    plt.savefig(graph_path, dpi=300, bbox_inches="tight")
    plt.close("all")
    return graph_path


def plot_lag_function(results: dict):
    from tigramite import plotting as tp

    lag_path = FIG_DIR / "S6_PCMCI_lag_functions.png"
    plt.figure(figsize=(12, 8))
    tp.plot_lagfuncs(
        val_matrix=results["val_matrix"],
        setup_args={"var_names": VAR_NAMES, "x_base": 5, "y_base": 0.5},
    )
    plt.savefig(lag_path, dpi=300, bbox_inches="tight")
    plt.close("all")
    return lag_path


def write_summary(df: pd.DataFrame, links: pd.DataFrame, graph_path: Path, lag_path: Path, method_name: str):
    sig = links[links["significant_q_alpha"]].copy()

    summary = {
        "method": method_name,
        "n_years": int(len(df)),
        "years_start": int(df.index.min()),
        "years_end": int(df.index.max()),
        "tau_min": TAU_MIN,
        "tau_max": TAU_MAX,
        "pc_alpha": PC_ALPHA,
        "alpha_level_fdr": ALPHA_LEVEL,
        "variables": VAR_NAMES,
        "use_ascent_instead_of_omega": USE_ASCENT_INSTEAD_OF_OMEGA,
        "n_significant_links": int(len(sig)),
        "significant_links": sig.head(30).to_dict(orient="records"),
        "graph": str(graph_path),
        "lag_functions": str(lag_path),
    }

    out = FIG_DIR / "S6_PCMCI_summary.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    return out


