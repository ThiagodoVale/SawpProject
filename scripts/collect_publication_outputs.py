from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from datetime import UTC, datetime
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = PROJECT_ROOT / "src"
if str(SOURCE_ROOT) not in sys.path:
    sys.path.insert(0, str(SOURCE_ROOT))

from sawp.publication import PUBLICATION_PRODUCTS  # noqa: E402


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Collect the outputs regenerated by the original publication scripts"
    )
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--destination", type=Path, default=PROJECT_ROOT / "results" / "figures")
    args = parser.parse_args()
    workspace = args.workspace.resolve()
    destination = args.destination.resolve()
    destination.mkdir(parents=True, exist_ok=True)
    reports = []
    for product in PUBLICATION_PRODUCTS:
        source = workspace / product.source_output
        script = workspace / product.producer_script
        if not source.is_file():
            raise FileNotFoundError(f"missing original-script output: {source}")
        if not script.is_file():
            raise FileNotFoundError(f"missing producer script: {script}")
        output = destination / product.filename
        shutil.copy2(source, output)
        metadata = {
            "schema_version": 2,
            "product_id": product.product_id,
            "source_kind": "generated_by_original_publication_script",
            "producer_script": str(script),
            "producer_script_sha256": _sha256(script),
            "source_output": str(source),
            "output": str(output),
            "sha256": _sha256(output),
            "bytes": output.stat().st_size,
            "matplotlib_version_expected": product.matplotlib_version,
            "created_utc": datetime.now(UTC).isoformat(),
        }
        output.with_suffix(output.suffix + ".json").write_text(
            json.dumps(metadata, indent=2), encoding="utf-8"
        )
        reports.append(metadata)
        print(f"{product.product_id}: {source} -> {output}")
    report = destination.parent / "publication_collection_report.json"
    report.write_text(json.dumps({"products": reports}, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
